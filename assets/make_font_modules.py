#!/usr/bin/env python3
"""
Prepare the certificate fonts for the serverless runtime.

Vercel/Node functions cannot rely on reading files from the deployment bundle,
so the fonts are embedded as base64 in a JS module (same approach as the
template artwork).

Steps per font:
  1. (Cinzel only) instance the variable font to a static Bold at wght=700 so
     pdf-lib/fontkit receives an ordinary TTF.
  2. subset to the glyphs a certificate can actually contain (basic Latin,
     Latin-1 for accented names, and common typographic punctuation).
  3. base64 -> src/lib/certificateFonts.js

This keeps the JS payload small enough to stay comfortably inside a serverless
function bundle.

Usage:  python3 assets/make_font_modules.py
"""

import base64
import os

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FD = os.path.join(ROOT, "assets", "fonts")
BUILD = os.path.join(ROOT, "assets", "fonts", "build")
OUT_JS = os.path.join(ROOT, "src", "lib", "certificateFonts.js")

os.makedirs(BUILD, exist_ok=True)

# Basic Latin + Latin-1 Supplement + common typographic marks.
UNICODES = (
    list(range(0x0020, 0x007F))      # ASCII printable
    + list(range(0x00A0, 0x0100))    # Latin-1 supplement (accented names)
    + [0x2018, 0x2019, 0x201C, 0x201D,   # curly quotes
       0x2013, 0x2014,                    # en/em dash
       0x2022,                            # bullet
       0x00B7,                            # middle dot
       0x2726,                            # four-pointed star (footer separator)
       0x2039, 0x203A]                    # single guillemets
)

# export name in the JS module -> (source file, variable axis instance)
FONTS = {
    "CinzelBold": ("Cinzel-var.ttf", {"wght": 700}),
    "CinzelDecorativeBold": ("CinzelDecorative-Bold.ttf", None),
    "CrimsonRegular": ("CrimsonText-Regular.ttf", None),
    "CrimsonItalic": ("CrimsonText-Italic.ttf", None),
    "CrimsonBold": ("CrimsonText-Bold.ttf", None),
    "GreatVibes": ("GreatVibes-Regular.ttf", None),
}


def subset_font(src_path, out_path):
    opts = subset.Options()
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.name_legacy = True
    opts.name_languages = ["*"]
    opts.notdef_outline = True
    opts.recalc_bounds = True
    opts.drop_tables = ["DSIG"]

    font = subset.load_font(src_path, opts)
    s = subset.Subsetter(options=opts)
    s.populate(unicodes=UNICODES)
    s.subset(font)
    subset.save_font(font, out_path, opts)
    font.close()


def prepare(name, filename, axes):
    src = os.path.join(FD, filename)
    if axes:
        out = os.path.join(BUILD, f"{name}-static.ttf")
        f = TTFont(src)
        instantiateVariableFont(f, axes, inplace=True, updateFontNames=True)
        f.save(out)
        f.close()
        src = out
    out = os.path.join(BUILD, f"{name}.subset.ttf")
    subset_font(src, out)
    return out


def main():
    entries = []
    for name, (filename, axes) in FONTS.items():
        p = prepare(name, filename, axes)
        size = os.path.getsize(p)
        with open(p, "rb") as f:
            b64 = base64.b64encode(f.read()).decode("ascii")
        entries.append((name, b64, size))
        print(f"  {name:<22} {size // 1024:>4} KB raw   {len(b64) // 1024:>4} KB b64")

    lines = [
        "// AUTO-GENERATED by assets/make_font_modules.py — do not edit.",
        "//",
        "// Certificate typefaces, subset to Latin-1 + typographic punctuation and",
        "// base64-embedded so serverless functions never touch the filesystem.",
        "//",
        "// All six are SIL Open Font License 1.1; the licence texts live in",
        "// assets/fonts/OFL-*.txt and are redistributed unchanged.",
        "//",
        "//   Cinzel / Cinzel Decorative ......... Natanael Gama (OFL)",
        "//   Crimson Text ...................... Sebastian Kosch (OFL)",
        "//   Great Vibes ....................... TypeSETit (OFL)",
        "",
    ]
    for name, b64, _ in entries:
        lines.append(f"export const {name} =")
        # wrap so the file stays diff-able / editor-friendly
        for i in range(0, len(b64), 120):
            lines.append(f"  '{b64[i:i + 120]}' +")
        lines[-1] = lines[-1].rstrip(" +")
        lines.append("")

    with open(OUT_JS, "w") as f:
        f.write("\n".join(lines))

    total = sum(len(b) for _, b, _ in entries)
    print(f"\nwrote {os.path.relpath(OUT_JS, ROOT)}  ({total // 1024} KB base64)")


if __name__ == "__main__":
    main()
